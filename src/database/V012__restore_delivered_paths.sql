-- =====================================================================
-- V012：恢复请求记录已交付文件集合（审查 P1-7）
--
-- 原实现在单文件下载分支里以「这一个文件传完了」作为整个恢复请求的完成判据，
-- 于是一个 50 文件的备份集，用户取走第 1 个文件，请求就变成 Completed——
-- 审计记录、待办队列、恢复统计随之全部失真。
--
-- 判定完成需要知道「已经交付了哪些文件」，因此在请求上记录已交付的相对路径集合。
-- 用 jsonb 数组存储：集合规模等于备份集文件数，量级可控，且便于排查时直接查看。
-- =====================================================================

ALTER TABLE restore_requests
    ADD COLUMN IF NOT EXISTS delivered_paths jsonb NOT NULL DEFAULT '[]'::jsonb;

COMMENT ON COLUMN restore_requests.delivered_paths IS
    '已完整交付的文件相对路径数组（V012，审查 P1-7）。整包 ZIP 下载直接置为完成，不依赖本列。';

-- V013：保留清理回收熔断阈值（审查 P1-2 配套）
--
-- 单个任务在一轮清理内拟回收的备份集比例达到该百分比时，判定为策略配置异常
-- 而非正常轮换，暂停该任务本轮回收并升级为严重告警。
--
-- 典型触发场景就是 P1-2 描述的那份「四项 Keep*Count 留空」的合法策略：
-- 它会让某任务全部备份集一次性进回收站。DTO 层的跨字段校验已经挡住新建这类策略，
-- 这道熔断负责挡住历史遗留策略、直接改库、以及尚未想到的其他成因。
--
-- 取值 1~100；100 表示关闭熔断。
-- =====================================================================

INSERT INTO system_settings (setting_key, setting_value, encrypted, updated_by)
VALUES ('retention_recycle_breaker_percent', '50'::jsonb, false, NULL)
ON CONFLICT (setting_key) DO NOTHING;

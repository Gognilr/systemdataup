-- =====================================================================
-- V025：仓库孤儿目录对帐相关系统配置
--
-- 入库的最后两步是 Directory.Move（提交目录改名为正式目录）和 SaveChangesAsync
-- （备份集写库）。进程崩在这两步之间——断电、蓝屏、手工重启服务——文件就留在
-- 仓库里而数据库没有任何记录：界面显示那次备份失败，实际盘上已有一份完整备份，
-- 而且没有任何巡检会发现它，仓库一点点被填满直到写不下。
-- UploadCommitWorker 的回滚路径处理了异常，但处理不了进程根本没机会跑回滚。
--
-- RepositoryReconcileWorker 负责把这些目录找出来告警——**只报不删**：
-- 每一个都可能是货真价实的备份，删错了没有第二份。
--
-- 全部幂等：已存在的键不覆盖，管理员改过的值不会被回滚。
-- =====================================================================

INSERT INTO system_settings (setting_key, setting_value, encrypted, updated_by) VALUES
    -- 对帐间隔（秒）。单轮要走一遍整个仓库目录树，配得太密只是白白搅动磁盘；
    -- 而孤儿目录不会自己长大，6 小时发现一次足够。下限 300 秒。
    ('repository_reconcile_interval_seconds', '21600'::jsonb, false, NULL),

    -- 判定为孤儿前的静默期（小时）。正在进行的入库本来就长着一副孤儿相：
    -- 提交目录已建好、库里还没有行。静默期必须宽到覆盖最慢的一次入库，
    -- 否则每轮都会把正在干活的目录报成残骸。
    ('repository_reconcile_grace_hours',      '24'::jsonb,    false, NULL)
ON CONFLICT (setting_key) DO NOTHING;

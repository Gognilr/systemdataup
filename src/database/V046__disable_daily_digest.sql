-- V046 关掉每日摘要
--
-- 日报原本担着两件事：证明系统还活着，以及给一份当天的数字。两件都有人接手了：
--
--   「系统还活着」→ 备份计划完成回执。每次计划跑完就发，粒度比一天细得多。
--   「当天的数字」→ 同一条回执里已经写清了共几项、成功几项、入库几份共多大。
--
-- 剩下的是纯粹的坏处：备份是每周一两次，于是七封日报里有五六封写着
-- 「0 份入库，昨天没有发现问题」。一条每天都一样、还说着「什么都没发生」的消息，
-- 人看三天就开始自动划过去——而这个习惯会传染到旁边真正的告警上。
-- 报警的可信度是整体的，摊薄了就都没了。
--
-- 这是一次「关掉」，不是「删掉」：DailyDigestWorker 和全部配置项都留着，
-- 想恢复时把这个键改回 true 即可（备份节奏变密之后它会重新变得有意义）。
UPDATE system_settings
SET setting_value = 'false'::jsonb, updated_at = now()
WHERE setting_key = 'daily_digest_enabled';

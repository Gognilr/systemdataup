-- V044 备份成功回执（按任务开关）
--
-- 此前通知一律是「出事才响」。而「今天这个任务到底做成没有」这个问题，
-- 只能等到第二天的日报，或者自己去管理页面翻。
--
-- 做成按任务勾选而不是一个全局开关，是因为这类通知的数量直接决定它的价值：
-- 每台机器每个任务每天成功一次，几台机器就是每天几十条。收件人一旦开始
-- 习惯性划过这些「都挺好」的消息，「备份复查未通过」也会跟着一起被划过去——
-- 报警的可信度是整体的，摊薄了就都没了。
--
-- 所以默认 false：只给真正要盯的那几个任务打开（比如核心库的全量备份），
-- 日志类、临时性的任务不开。产生之后发给哪些渠道，仍由各渠道的
-- 「另外排除这些类别」决定（类别键 backup_succeeded）。
ALTER TABLE backup_tasks ADD COLUMN IF NOT EXISTS notify_on_success boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN backup_tasks.notify_on_success IS
    '这个任务备份成功后是否发一条回执通知；默认关闭，只给要紧的任务打开';
